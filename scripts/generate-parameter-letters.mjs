import {writeFileSync} from 'node:fs';

globalThis.grammar = (definition) => definition;
globalThis.token = (rule) => rule;
globalThis.choice = (...rules) => rules;

const root = new URL('../', import.meta.url);
const {default: definition} = await import(new URL('grammar.js', root));
const pattern = definition.rules.command_parameter({_bare_dashes: null})[0][0];
if (!(pattern instanceof RegExp)) {
  throw new Error('Expected the first command parameter rule to be a regular expression');
}
const parameter = new RegExp(`^(?:${pattern.source})$`, pattern.flags);
const ranges = [];
for (let code = 0x80; code <= 0xffff; code++) {
  if (!parameter.test(`-${String.fromCharCode(code)}`)) continue;
  const previous = ranges[ranges.length - 1];
  if (previous && previous[1] === code - 1) previous[1] = code;
  else ranges.push([code, code]);
}
const entries = ranges.map(([start, end]) =>
  `    {0x${start.toString(16)}, 0x${end.toString(16)}},`).join('\n');
writeFileSync(new URL('src/parameter_letters.h', root), `\
/* Generated by scripts/generate-parameter-letters.mjs from grammar.js. */
#ifndef POWERSHELL_PARAMETER_LETTERS_H
#define POWERSHELL_PARAMETER_LETTERS_H
#include <stdbool.h>
#include <stdint.h>

static const struct { uint16_t first, last; } parameter_letters[] = {
${entries}
};

static inline bool is_unicode_parameter_letter(int32_t code)
{
    if (code < 0x80 || code > 0xffff) return false;
    unsigned left = 0, right = sizeof(parameter_letters) / sizeof(parameter_letters[0]);
    while (left < right) {
        unsigned middle = left + (right - left) / 2;
        if (code < parameter_letters[middle].first) right = middle;
        else if (code > parameter_letters[middle].last) left = middle + 1;
        else return true;
    }
    return false;
}
#endif
`);
