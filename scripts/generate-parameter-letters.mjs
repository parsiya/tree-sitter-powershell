import {writeFileSync} from 'node:fs';

globalThis.grammar = (definition) => definition;
globalThis.token = (rule) => rule;
globalThis.choice = (...rules) => rules;
globalThis.seq = (...rules) => rules;
globalThis.optional = (rule) => rule;
globalThis.prec = (_, rule) => rule;
globalThis.alias = (rule) => rule;

const root = new URL('../', import.meta.url);
const {default: definition} = await import(new URL('grammar.js', root));
const pattern = definition.rules.command_parameter({_bare_dashes: null})[0][0];
if (!(pattern instanceof RegExp)) {
  throw new Error('Expected the first command parameter rule to be a regular expression');
}
const parameter = new RegExp(`^(?:${pattern.source})$`, pattern.flags);
const variablePattern = definition.rules.variable({braced_variable: null}).flat(Infinity)
  .find((rule) => rule instanceof RegExp && rule.source.includes('\\P{Nd}'));
if (!variablePattern) {
  throw new Error('Expected a Unicode letter/digit rule in variable names');
}
const variable = new RegExp(`^(?:${variablePattern.source})$`, variablePattern.flags);
const toRanges = (predicate) => {
  const ranges = [];
  for (let code = 0x80; code <= 0xffff; code++) {
    if (!predicate(String.fromCharCode(code))) continue;
    const previous = ranges[ranges.length - 1];
    if (previous && previous[1] === code - 1) previous[1] = code;
    else ranges.push([code, code]);
  }
  return ranges.map(([start, end]) =>
    `    {0x${start.toString(16)}, 0x${end.toString(16)}},`).join('\n');
};
const parameterEntries = toRanges((character) => parameter.test(`-${character}`));
const digitEntries = toRanges((character) => variable.test(character) && !parameter.test(`-${character}`));
writeFileSync(new URL('src/parameter_letters.h', root), `\
/* Generated by scripts/generate-parameter-letters.mjs from grammar.js. */
#ifndef POWERSHELL_PARAMETER_LETTERS_H
#define POWERSHELL_PARAMETER_LETTERS_H
#include <stdbool.h>
#include <stdint.h>

typedef struct { uint16_t first, last; } UnicodeNameRange;
static const UnicodeNameRange parameter_letters[] = {
${parameterEntries}
};
static const UnicodeNameRange variable_digits[] = {
${digitEntries}
};

static inline bool unicode_name_contains(const UnicodeNameRange *ranges, unsigned length, int32_t code)
{
    if (code < 0x80 || code > 0xffff) return false;
    unsigned left = 0, right = length;
    while (left < right) {
        unsigned middle = left + (right - left) / 2;
        if (code < ranges[middle].first) right = middle;
        else if (code > ranges[middle].last) left = middle + 1;
        else return true;
    }
    return false;
}

static inline bool is_unicode_parameter_letter(int32_t code)
{
    return unicode_name_contains(parameter_letters, sizeof(parameter_letters) / sizeof(parameter_letters[0]), code);
}

static inline bool is_unicode_variable_digit(int32_t code)
{
    return unicode_name_contains(variable_digits, sizeof(variable_digits) / sizeof(variable_digits[0]), code);
}
#endif
`);
