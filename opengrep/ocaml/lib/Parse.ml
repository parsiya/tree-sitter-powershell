and trans_unary_expression ((kind, body) : mt) : CST.unary_expression =
  match body with
  | Children v ->
      (match v with
      | Alt (0, v) ->
          `Prim_exp (
            trans_primary_expression (Run.matcher_token v)
          )
      | Alt (1, v) ->
          `Exp_with_un_op (
            trans_expression_with_unary_operator (Run.matcher_token v)
          )
      | _ -> assert false
      )
  | Leaf _ -> assert false

and trans_value ((kind, body) : mt) : CST.value =
  match body with
  | Children v ->
      (match v with
      | Alt (0, v) ->
          `Paren_exp (
            trans_parenthesized_expression (Run.matcher_token v)
          )
      | Alt (1, v) ->
          `Sub_exp (
            trans_sub_expression (Run.matcher_token v)
          )
      | Alt (2, v) ->
          `Array_exp (
            trans_array_expression (Run.matcher_token v)
          )
      | Alt (3, v) ->
          `Script_blk_exp (
            trans_script_block_expression (Run.matcher_token v)
          )
      | Alt (4, v) ->
          `Hash_lit_exp (
            trans_hash_literal_expression (Run.matcher_token v)
          )
      | Alt (5, v) ->
          `Lit (
            trans_literal (Run.matcher_token v)
          )
      | Alt (6, v) ->
          `Type_lit (
            trans_type_literal (Run.matcher_token v)
          )
      | Alt (7, v) ->
          `Var (
            trans_variable (Run.matcher_token v)
          )
      | _ -> assert false
      )
  | Leaf _ -> assert false

and trans_while_condition ((kind, body) : mt) : CST.while_condition =
  match body with
  | Children v ->
      trans_pipeline (Run.matcher_token v)
  | Leaf _ -> assert false

and trans_while_statement ((kind, body) : mt) : CST.while_statement =
  match body with
  | Children v ->
      (match v with
      | Seq [v0; v1; v2; v3; v4] ->
          (
            trans_pat_while (Run.matcher_token v0),
            Run.trans_token (Run.matcher_token v1),
            trans_while_condition (Run.matcher_token v2),
            Run.trans_token (Run.matcher_token v3),
            trans_statement_block (Run.matcher_token v4)
          )
      | _ -> assert false
      )
  | Leaf _ -> assert false

let trans_using_statement ((kind, body) : mt) : CST.using_statement =
  match body with
  | Children v ->
      (match v with
      | Seq [v0; v1] ->
          (
            trans_pat_using (Run.matcher_token v0),
            (match v1 with
            | Alt (0, v) ->
                `Pat_name_choice_type_name (
                  (match v with
                  | Seq [v0; v1] ->
                      (
                        trans_pat_name (Run.matcher_token v0),
                        (match v1 with
                        | Alt (0, v) ->
                            `Type_name (
                              trans_type_name (Run.matcher_token v)
                            )
                        | Alt (1, v) ->
                            `Str_lit (
                              trans_string_literal (Run.matcher_token v)
                            )
                        | _ -> assert false
                        )
                      )
                  | _ -> assert false
                  )
                )
            | Alt (1, v) ->
                `Pat_module_choice_str_lit (
                  (match v with
                  | Seq [v0; v1] ->
                      (
                        trans_pat_module (Run.matcher_token v0),
                        (match v1 with
                        | Alt (0, v) ->
                            `Str_lit (
                              trans_string_literal (Run.matcher_token v)
                            )
                        | Alt (1, v) ->
                            `Hash_lit_exp (
                              trans_hash_literal_expression (Run.matcher_token v)
                            )
                        | Alt (2, v) ->
                            `Cmd_word (
                              trans_command_word (Run.matcher_token v)
                            )
                        | _ -> assert false
                        )
                      )
                  | _ -> assert false
                  )
                )
            | Alt (2, v) ->
                `Pat_asse_choice_str_lit (
                  (match v with
                  | Seq [v0; v1] ->
                      (
                        trans_pat_asse (Run.matcher_token v0),
                        (match v1 with
                        | Alt (0, v) ->
                            `Str_lit (
                              trans_string_literal (Run.matcher_token v)
                            )
                        | Alt (1, v) ->
                            `Cmd_word (
                              trans_command_word (Run.matcher_token v)
                            )
                        | _ -> assert false
                        )
                      )
                  | _ -> assert false
                  )
                )
            | _ -> assert false
            )
          )
      | _ -> assert false
      )
  | Leaf _ -> assert false

let trans_program ((kind, body) : mt) : CST.program =
  match body with
  | Children v ->
      (match v with
      | Seq [v0; v1; v2; v3] ->
          (
            Run.opt
              (fun v -> trans_leading_bom (Run.matcher_token v))
              v0
            ,
            Run.repeat
              (fun v ->
                (match v with
                | Seq [v0; v1; v2] ->
                    (
                      trans_using_statement (Run.matcher_token v0),
                      trans_statement_terminator (Run.matcher_token v1),
                      Run.opt
                        (fun v -> trans_using_separator (Run.matcher_token v))
                        v2
                    )
                | _ -> assert false
                )
              )
              v1
            ,
            Run.opt
              (fun v -> trans_param_block (Run.matcher_token v))
              v2
            ,
            Run.opt
              (fun v ->
                (match v with
                | Alt (0, v) ->
                    `Stmt_list (
                      trans_statement_list (Run.matcher_token v)
                    )
                | Alt (1, v) ->
                    `Named_blk_list (
                      trans_named_block_list (Run.matcher_token v)
                    )
                | _ -> assert false
                )
              )
              v3
          )
      | _ -> assert false
      )
  | Leaf _ -> assert false

(*
   Costly operation that translates a whole tree or subtree.

   The first pass translates it into a generic tree structure suitable
   to guess which node corresponds to each grammar rule.
   The second pass is a translation into a typed tree where each grammar
   node has its own type.

   This function is called:
   - once on the root of the program after removing extras
     (comments and other nodes that occur anywhere independently from
     the grammar);
   - once of each extra node, resulting in its own independent tree of type
     'extra'.
*)
let translate_tree src node trans_x =
  let matched_tree = Run.match_tree children_regexps src node in
  Option.map trans_x matched_tree


let translate_extra src (node : Tree_sitter_output_t.node) : CST.extra option =
  match node.type_ with
  | "comment" ->
      (match translate_tree src node trans_comment with
      | None -> None
      | Some x -> Some (`Comment (Run.get_loc node, x)))
  | "spaces_before_comma" ->
      (match translate_tree src node trans_spaces_before_comma with
      | None -> None
      | Some x -> Some (`Spaces_before_comma (Run.get_loc node, x)))
  | _ -> None

let translate_root src root_node =
  translate_tree src root_node trans_program

let parse_input_tree input_tree =
  let orig_root_node = Tree_sitter_parsing.root input_tree in
  let src = Tree_sitter_parsing.src input_tree in
  let errors = Run.extract_errors src orig_root_node in
  let opt_program, extras =
     Run.translate
       ~extras
       ~translate_root:(translate_root src)
       ~translate_extra:(translate_extra src)
       orig_root_node
  in
  Parsing_result.create src opt_program extras errors

let string ?src_file contents =
  let input_tree = parse_source_string ?src_file contents in
  parse_input_tree input_tree

let file src_file =
  let input_tree = parse_source_file src_file in
  parse_input_tree input_tree

